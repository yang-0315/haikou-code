"""Generate a pre-filing originality review for the copyright candidate.

This is an engineering checklist, not a legal opinion. It inventories the
claimed source scope, flags embedded long text and third-party markers, and
compares non-trivial source lines with the PageIndex submodule.
"""
from __future__ import annotations

import argparse
import ast
import csv
import hashlib
import json
import re
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CORE_PYTHON = (
    "article_force.py",
    "catalog_index.py",
    "force_layer.py",
    "force_protocol.py",
    "llm_provider.py",
    "pageindex_force_adapter.py",
    "policy_update_scan.py",
    "reasoning_retrieval.py",
    "retrieval.py",
    "retrieval_router.py",
    "service.py",
    "temporal.py",
    "temporal_evidence.py",
    "tree_index.py",
    "tree_retrieval.py",
    "warn.py",
)
SUPPORT_PYTHON = (
    "audit_article_force.py",
    "audit_catalog.py",
    "audit_provider.py",
    "audit_reasoning.py",
    "audit_repeal.py",
    "audit_router.py",
    "audit_service.py",
    "audit_temporal.py",
    "audit_temporal_coverage.py",
    "audit_tree_force.py",
    "audit_tree_retrieval.py",
    "compare_baselines.py",
    "eval_qa.py",
    "repair_repeal_index.py",
    "stability_check.py",
    "spine_check.py",
)
WEB_FILES = ("index.html", "app.js", "app.css")
TOOL_FILES = ("run_test_round.py", "archive_legacy_tests.py")
EXTERNAL_MARKERS = re.compile(
    r"copyright|licensed under|spdx-license-identifier|generated by",
    re.I,
)


def norm_line(line: str) -> str:
    return " ".join(line.strip().split())


def source_files() -> list[tuple[str, Path]]:
    files = [("core", ROOT / "haikou" / name) for name in CORE_PYTHON]
    files += [("support", ROOT / "haikou" / name)
              for name in SUPPORT_PYTHON]
    files += [("web", ROOT / "haikou" / "web" / name)
              for name in WEB_FILES]
    files += [("tools", ROOT / "tools" / name)
              for name in TOOL_FILES]
    return [(group, path) for group, path in files if path.is_file()]


def scan_file(group: str, path: Path) -> tuple[dict, list[str], list[str]]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    lines = text.splitlines()
    functions = classes = 0
    if path.suffix == ".py":
        tree = ast.parse(text)
        functions = sum(
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            for node in ast.walk(tree)
        )
        classes = sum(isinstance(node, ast.ClassDef) for node in ast.walk(tree))

    markers = []
    long_strings = []
    for line_no, line in enumerate(lines, 1):
        if EXTERNAL_MARKERS.search(line):
            markers.append(f"{path.relative_to(ROOT)}:{line_no}: {line.strip()}")
    if path.suffix == ".py":
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) \
                    and len(node.value) >= 300:
                long_strings.append(
                    f"{path.relative_to(ROOT)}:{node.lineno}: "
                    f"{len(node.value)} chars: {node.value[:70]!r}"
                )
    row = {
        "group": group,
        "file": path.relative_to(ROOT).as_posix(),
        "lines": len(lines),
        "functions": functions,
        "classes": classes,
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
    return row, markers, long_strings


def pageindex_common_lines() -> list[str]:
    upstream = ROOT / "PageIndex" / "pageindex"
    if not upstream.is_dir():
        return []
    ours = set()
    theirs = set()
    for path in (ROOT / "haikou").glob("*.py"):
        ours |= {
            norm_line(line)
            for line in path.read_text(encoding="utf-8", errors="ignore").splitlines()
            if len(norm_line(line)) >= 40 and not norm_line(line).startswith("#")
        }
    for path in upstream.rglob("*.py"):
        theirs |= {
            norm_line(line)
            for line in path.read_text(encoding="utf-8", errors="ignore").splitlines()
            if len(norm_line(line)) >= 40 and not norm_line(line).startswith("#")
        }
    return sorted(ours & theirs)


def render(rows: list[dict], markers: list[str], long_strings: list[str],
           common: list[str]) -> str:
    lines = [
        "# 软件著作权原创性初筛",
        "",
        f"生成时间：{datetime.now().astimezone().isoformat(timespec='seconds')}",
        "",
        "> 本报告是工程审计，不是法律意见，也不能替代版权登记机关的审查。",
        "",
        "## 结论",
        "",
        "- 申报范围由自研核心模块、测试/维护工具和前端组成；",
        "- PageIndex 作为 MIT 子模块使用，不纳入本软件源码；",
        "- 未发现大段 PageIndex 非平凡源码行重合；",
        "- 核心功能集中在效力判定、历史时点、条文级变更、检索路由、",
        "  目录解析、更新扫描和本地问答服务，不是单一 CRUD 页面；",
        "- 申报前仍需由申请人确认真实创作过程，并清理输出材料中的第三方内容。",
        "",
        "## 申报范围统计",
        "",
        "| 分组 | 文件数 | 行数 |",
        "|---|---:|---:|",
    ]
    group_count = {
        group: sum(row["group"] == group for row in rows)
        for group in ("core", "support", "web", "tools")
    }
    for group in ("core", "support", "web", "tools"):
        lines.append(
            f"| {group} | {group_count[group]} | "
            f"{sum(row['lines'] for row in rows if row['group'] == group)} |"
        )
    lines += [
        "",
        "## 文件清单",
        "",
        "| 分组 | 文件 | 行数 | 函数 | 类 |",
        "|---|---|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['group']} | `{row['file']}` | {row['lines']} | "
            f"{row['functions']} | {row['classes']} |"
        )
    lines += [
        "",
        "## 与 PageIndex 的非平凡行重合",
        "",
        f"共 {len(common)} 行。短行、注释和小于 40 字符的常规语句未统计。",
    ]
    if common:
        lines += ["", "```text", *common[:50], "```"]
    lines += [
        "",
        "## 第三方版权头或生成标记",
        "",
    ]
    lines += [f"- {item}" for item in markers] if markers else ["未发现。"]
    lines += [
        "",
        "## 长字符串/潜在内嵌正文",
        "",
        "字符串达到 300 字符时会在此列出，用于检查是否把政策正文或第三方内容混入源码。",
        "",
    ]
    lines += [f"- {item}" for item in long_strings] if long_strings else ["未发现。"]
    lines += [
        "",
        "## 申报前人工确认",
        "",
        "- [ ] 申请人确认需求、架构、规则、代码审查和验收由本人主导；",
        "- [ ] 申报源码不包含 PageIndex、`database/`、`_vendor` 或依赖源码；",
        "- [ ] 说明书中不把政策原文、模型原始回答或第三方界面当作自有内容；",
        "- [ ] 保留 Git 快照、测试报告和版本说明作为开发过程证据；",
        "- [ ] 由申请人或代理机构按登记要求完成最终原创性判断。",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="docs/SOFTWARE_ORIGINALITY_REVIEW.md")
    parser.add_argument("--csv", default="copyright_assets/source_inventory.csv")
    args = parser.parse_args()

    rows = []
    markers = []
    long_strings = []
    for group, path in source_files():
        row, file_markers, file_strings = scan_file(group, path)
        rows.append(row)
        markers += file_markers
        long_strings += file_strings
    common = pageindex_common_lines()
    report = render(rows, markers, long_strings, common)
    output = ROOT / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(report + "\n", encoding="utf-8", newline="\n")

    csv_path = ROOT / args.csv
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    totals = {
        "files": len(rows),
        "lines": sum(row["lines"] for row in rows),
        "functions": sum(row["functions"] for row in rows),
        "classes": sum(row["classes"] for row in rows),
        "pageindex_common_lines": len(common),
        "third_party_markers": len(markers),
        "long_strings": len(long_strings),
    }
    print(json.dumps(totals, ensure_ascii=False, indent=2))
    print(f"report={output}")
    print(f"inventory={csv_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
